// Regenerates src/lib/nav/route-index.ts from the /tenant-admin page tree.
// Run from the repo root: node scripts/gen-route-index.mjs
// Labels and sections already in the file are kept; new pages get a
// humanized label from their path.
import fs from "node:fs";
import path from "node:path";

const ROOT = "src/app/tenant-admin";
const OUT = "src/lib/nav/route-index.ts";

const existing = new Map();
if (fs.existsSync(OUT)) {
  const src = fs.readFileSync(OUT, "utf8");
  for (const m of src.matchAll(/href: ("[^"]*"), label: ("[^"]*"), section: ("[^"]*")/g)) {
    existing.set(JSON.parse(m[1]), { label: JSON.parse(m[2]), section: JSON.parse(m[3]) });
  }
}

const routes = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === "page.tsx") {
      routes.push("/" + path.relative("src/app", dir).split(path.sep).join("/"));
    }
  }
})(ROOT);

const human = (s) => s.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

const rows = routes.sort().map((href) => {
  const seg = href.split("/").filter(Boolean);
  const prev = existing.get(href);
  const leaf = seg[seg.length - 1];
  const label = prev?.label ?? (leaf === "tenant-admin" ? "Dashboard" : human(leaf));
  const section = prev?.section ?? (seg[1] ? human(seg[1]) : "");
  return `  { href: ${JSON.stringify(href)}, label: ${JSON.stringify(label)}, section: ${JSON.stringify(section)} },`;
});

const out = `/** GENERATED by scripts/gen-route-index.mjs — every /tenant-admin page route,
 *  for the global search index. Re-run the script after adding pages. */
export const ROUTE_INDEX: Array<{ href: string; label: string; section: string }> = [
${rows.join("\n")}
];
`;

fs.writeFileSync(OUT, out);
const added = routes.filter((r) => !existing.has(r));
console.log(`route-index: ${routes.length} routes, ${added.length} new${added.length ? ": " + added.join(", ") : ""}`);
